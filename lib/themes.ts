export function getTheme(id: string): ThemeDefinition {
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}

export type ThemeDecor = "none" | "blobs" | "grid" | "dots" | "ring" | "rays";

export interface ResolvedThemeTokens {
  decor: ThemeDecor;
  shadow: string;
  cardEffect: "solid" | "glass" | "soft";
  buttonShape: "pill" | "rounded" | "sharp";
  divider: string;
  decorColors: string[];
}

/**
 * Phase 1 — Theme Design Tokens: derives a complete visual identity from each
 * theme's palette/fonts/geometry so every theme renders distinctly, not just
 * different accent colors.
 */
export function resolveThemeTokens(theme: ThemeDefinition): ResolvedThemeTokens {
  const cat = theme.category;
  const id = theme.id;

  let decor: ThemeDecor = "none";
  if (cat === "glassmorphism" || cat === "gradient" || cat === "modern" || cat === "technology" || id.includes("mesh") || id.includes("ai")) decor = "blobs";
  else if (cat === "vaporwave" || cat === "retro" || cat === "cyberpunk" || cat === "security" || id.includes("futuristic") || id.includes("holographic")) decor = "grid";
  else if (cat === "luxury" || id.includes("gold") || id.includes("magazine")) decor = "ring";
  else if (cat === "nature" || cat === "scientific" || id.includes("emerald") || id.includes("terra") || id.includes("esg")) decor = "dots";
  else if (id.includes("sunset") || id.includes("aurora") || id.includes("ocean")) decor = "rays";
  else if (theme.glass) decor = "blobs";

  const shadow = theme.glass
    ? theme.isDark ? "0 20px 60px rgba(0,0,0,0.45)" : "0 16px 44px rgba(17,24,39,0.12)"
    : theme.isDark ? "0 12px 32px rgba(0,0,0,0.5)" : "0 10px 30px rgba(17,24,39,0.08)";

  return {
    decor,
    shadow,
    cardEffect: theme.glass ? "glass" : theme.radius >= 18 ? "soft" : "solid",
    buttonShape: theme.radius >= 18 ? "pill" : theme.radius <= 6 ? "sharp" : "rounded",
    divider: theme.glass
      ? `linear-gradient(90deg, transparent, ${theme.primary}99, transparent)`
      : `linear-gradient(90deg, transparent, ${theme.border || "#ffffff33"}, transparent)`,
    decorColors: [theme.primary, theme.secondary || theme.accent, theme.accent || theme.primary],
  };
}

